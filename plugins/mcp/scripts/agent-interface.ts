/** Every file in the Claude Code plugin folder, relative and sorted. */
export function listPluginFiles(dir = join(pluginsRoot, 'claude-code')): string[] {
  const out: string[] = [];
  const walk = (d: string) => {
    for (const name of readdirSync(d)) {
      const path = join(d, name);
      if (statSync(path).isDirectory()) walk(path);
      else out.push(relative(dir, path).split('\\').join('/'));
    }
  };
  walk(dir);
  return out.sort();
}

const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ');

function fieldTable(rows: readonly { path: string; type: string; required: boolean; description: string }[]): string[] {
  if (!rows.length) return [];
  return [
    '| Field | Type | Required | Meaning |',
    '|---|---|---|---|',
    ...rows.map((r) => `| \`${r.path}\` | ${cell(r.type)} | ${r.required ? 'yes' : 'no'} | ${cell(r.description)} |`),
  ];
}

function toolInputRows(input: z.ZodObject) {
  const schema = z.toJSONSchema(input, { io: 'input', unrepresentable: 'any' }) as {
    properties?: Record<string, { type?: string | string[]; description?: string; enum?: unknown[]; anyOf?: { type?: string }[] }>;
    required?: string[];
  };
  const required = new Set(schema.required ?? []);
  return Object.entries(schema.properties ?? {}).map(([name, p]) => ({
    path: name,
    type: p.enum
      ? p.enum.map((v) => JSON.stringify(v)).join(' \\| ')
      : Array.isArray(p.type)
        ? p.type.join(' or ')
        : (p.type ?? (p.anyOf ? p.anyOf.map((a) => a.type ?? 'any').join(' or ') : 'any')),
    required: required.has(name),
    description: p.description ?? '',
  }));
}

